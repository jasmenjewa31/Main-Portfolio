// Static routing contract; run browser checks separately before publishing.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
const origin = 'https://jasmen.asia';
const routes = require('./routes.json');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const canonical = html => [...html.matchAll(/<link\b[^>]*rel="canonical"[^>]*href="([^"]+)"[^>]*>/g)].map(m => m[1]);
const expected = new Set(routes.map(route => origin + route.clean));
const sitemap = [...read('sitemap.xml').matchAll(/<loc>([^<]+)<\/loc>/g)].map(m => m[1]);
assert.equal(new Set(routes.map(route => route.old)).size, routes.length, 'Duplicate legacy route');
assert.equal(new Set(sitemap).size, sitemap.length, 'Duplicate sitemap URL');
assert.deepEqual(new Set(sitemap), expected, 'Sitemap must contain exactly the canonical documents');

for (const route of routes) {
  assert.equal(route.clean, route.clean.toLowerCase(), 'Canonical paths must be lowercase');
  assert.ok(!/\s|\/Projects\//.test(route.clean), 'Canonical paths must be clean');
  const target = read(route.file);
  assert.deepEqual(canonical(target), [origin + route.clean], route.file + ' canonical');
  assert.ok(target.includes('<meta property="og:url" content="' + origin + route.clean + '"'), route.file + ' Open Graph URL');
  const legacy = read(route.old.slice(1));
  assert.deepEqual(canonical(legacy), [origin + route.clean], route.old + ' canonical');
  const fallback = legacy.match(/http-equiv="refresh"\s+content="0;\s*url=([^"]+)"/i);
  assert.ok(fallback, route.old + ' refresh fallback');
  assert.equal(new URL(fallback[1], origin + route.old).href, origin + route.clean, route.old + ' refresh target');
  const link = legacy.match(/<a\b[^>]*href="([^"]+)"/);
  assert.ok(link, route.old + ' visible fallback');
  assert.equal(new URL(link[1], origin + route.old).href, origin + route.clean);
  for (const suffix of ['', '?source=legacy&value=%2F#section-2']) {
    let forwarded;
    const current = new URL(origin + route.old + suffix);
    const location = {href:current.href, search:current.search, hash:current.hash, replace:value => { forwarded = new URL(value, current).href; }};
    const context = {URL, location, window:{location}};
    const scripts = [...legacy.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)];
    assert.ok(scripts.length, route.old + ' forwarding script');
    for (const script of scripts) vm.runInNewContext(script[1], context, {timeout:1000});
    assert.equal(forwarded, origin + route.clean + suffix, route.old + ' query/fragment forwarding');
  }
}

// The seven project cards are generated by this published script.
const home = read('index.html');
const script = home.match(/src="(assets\/portfolio-sites\.[a-f0-9]+\.js)"/);
assert.ok(script, 'Homepage project navigation script');
const navigation = read(script[1]);
const links = [...navigation.matchAll(/url:\s*'([^']+)'/g)].map(m => m[1]);
assert.equal(links.length, 7, 'Seven project destinations');
for (const link of links) assert.ok(expected.has(origin + link), 'Noncanonical project link: ' + link);
assert.equal(navigation.replace(/\r\n/g, '\n'), read('Projects/Creative Portfolio/portfolio-sites.js').replace(/\r\n/g, '\n'), 'Cached homepage navigation must remain consistent');
console.log(`PASS: ${expected.size} canonical documents, ${routes.length} legacy redirects, seven project links, sitemap, query strings and fragments.`);
